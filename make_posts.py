    ImageDraw.Draw(mask).ellipse([size * 0.06, -size, size * 0.94, size * 0.98], fill=255)  # 丸からはみ出す肩を切る
    a = Image.composite(pc.getchannel("A"), Image.new("L", (size, size), 0), mask)
    pc.putalpha(a)
    im.paste(pc, (x, y), pc)

