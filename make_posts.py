def person(im, d, x, y, size, ring=LIGHT):
    """社長の切り抜き写真を水色の丸の上に置く"""
    d.ellipse([x + size * 0.06, y + size * 0.1, x + size * 0.94, y + size * 0.98], fill=ring)
    pc = PERSON.resize((size, size), Image.LANCZOS)
